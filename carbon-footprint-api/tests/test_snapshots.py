"""Vergleicht alle Endpunkte mit aufgezeichneten Antworten (Snapshot-Tests).

Die Referenzdaten in ``snapshots.tar.gz`` wurden mit ``tools/record_snapshots.py`` gegen diese API und die
Dateien in ``../repo`` aufgezeichnet. Ändert sich das Antwortformat gewollt, die Daten neu aufzeichnen
(siehe README) und die Version erhöhen.
"""

from __future__ import annotations

import base64
import hashlib
import json
import re
import tarfile
import urllib.parse
from pathlib import Path

import pytest

from carbon_footprint_api import API_PREFIX
from conftest import SNAPSHOT_ARCHIVE

_AUTO_ID = re.compile(r"(autogenerated_.*?_)[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")


def b64(s: str) -> str:
    return base64.urlsafe_b64encode(s.encode("utf-8")).decode("ascii")


def normalize(data):
    """Ersetzt die zufällige UUID in automatisch erzeugten globalAssetIds."""
    return json.loads(_AUTO_ID.sub(r"\1<uuid>", json.dumps(data, ensure_ascii=False)))


def snapshot_files() -> list[str]:
    if not SNAPSHOT_ARCHIVE.exists():
        return []
    with tarfile.open(SNAPSHOT_ARCHIVE) as tar:
        return sorted(
            Path(m.name).name
            for m in tar.getmembers()
            if m.name.endswith(".json") and not m.name.endswith("_common.json")
        )


def assert_matches(response, entry):
    where = entry["path"]
    assert response.status_code == entry["status"], where
    assert response.headers.get("content-type", "").split(";")[0].strip() == entry["contentType"], where
    if "body" in entry:
        body = response.json()
        expected = entry["body"]
        if entry["status"] >= 400 and isinstance(body, dict) and isinstance(expected, dict):
            body, expected = ({k: v for k, v in b.items() if k != "timestamp"} for b in (body, expected))
        assert normalize(body) == normalize(expected), where
    elif entry["status"] >= 400:
        pass  # binär aufgezeichnete Fehlerantwort: enthält einen Zeitstempel, Status und Typ genügen
    else:
        assert len(response.content) == entry["length"], where
        assert hashlib.sha256(response.content).hexdigest() == entry["sha256"], where


def test_common(client, snapshot_dir):
    common = json.loads((snapshot_dir / "_common.json").read_text("utf-8"))
    descriptors = client.get(API_PREFIX + "/shell-descriptors")
    assert descriptors.status_code == 200
    assert sorted(normalize(descriptors.json()["result"]), key=lambda d: d["id"]) == sorted(
        normalize(common["shell-descriptors"]["body"]["result"]), key=lambda d: d["id"]
    )
    assert_matches(client.get(API_PREFIX + "/asset/all"), common["asset-all"])
    for entry in common["errors"]:
        r = client.get(API_PREFIX + entry["path"])
        if "body" in entry and isinstance(entry["body"], dict):
            entry = {**entry, "body": {k: v for k, v in entry["body"].items() if k != "timestamp"}}
            assert r.status_code == entry["status"]
            assert {k: v for k, v in r.json().items() if k != "timestamp"} == entry["body"]
        else:
            assert_matches(r, entry)


@pytest.mark.parametrize("name", snapshot_files())
@pytest.mark.parametrize("by", ["byId", "byGlobalAssetId"])
def test_shell(client, repo_provider, snapshot_dir, name, by):
    record = json.loads((snapshot_dir / name).read_text("utf-8"))
    recorded = record[by]
    if not recorded:
        pytest.skip("keine Daten")
    shell_id = record["descriptor"]["id"]
    shell = repo_provider.get_shell(shell_id)
    assert shell is not None

    # Automatisch erzeugte globalAssetIds enthalten eine zufällige UUID: eigene ID statt der aufgezeichneten
    recorded_ident = shell_id if by == "byId" else record["descriptor"]["globalAssetId"]
    ident = shell_id if by == "byId" else shell["assetInformation"]["globalAssetId"]

    def get(entry):
        path = entry["path"].replace(b64(recorded_ident), b64(ident))
        path = path.replace(urllib.parse.quote(recorded_ident, safe=""), urllib.parse.quote(ident, safe=""))
        return client.get(API_PREFIX + path)

    for key in ("shell", "submodelRefs", "thumbnail"):
        assert_matches(get(recorded[key]), recorded[key])
    r = get(recorded["assetSubmodelAll"])
    assert r.status_code == 200 and sorted(r.json()) == sorted(recorded["assetSubmodelAll"]["body"])

    for entry in recorded["submodels"].values():
        assert_matches(get(entry["submodel"]), entry["submodel"])
        if "assetSubmodel" in entry:
            assert_matches(get(entry["assetSubmodel"]), entry["assetSubmodel"])
        for expected in entry["elements"].values():
            assert_matches(get(expected), expected)
        for expected in entry["attachments"].values():
            assert_matches(get(expected), expected)
